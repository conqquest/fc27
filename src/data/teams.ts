import type { Team, Player, Kit, Tactics, PlayerAttributes, Position } from './types'

function makeAttributes(
  pos: Position,
  tier: 'world-class' | 'star' | 'regular' = 'star',
  custom: Partial<PlayerAttributes> = {}
): PlayerAttributes {
  const base = tier === 'world-class' ? 86 : tier === 'star' ? 82 : 77

  const isGK = pos === 'GK'
  const isDef = ['CB', 'LB', 'RB'].includes(pos)
  const isMid = ['CDM', 'CM', 'CAM', 'LM', 'RM'].includes(pos)
  const isAtt = ['ST', 'CF', 'LW', 'RW'].includes(pos)

  const attrs: PlayerAttributes = {
    pace: isGK ? 45 : isAtt ? base + 6 : isMid ? base : base + 2,
    acceleration: isGK ? 48 : isAtt ? base + 6 : base,
    sprintSpeed: isGK ? 45 : isAtt ? base + 5 : base + 1,
    shooting: isAtt ? base + 5 : isMid ? base - 3 : 52,
    finishing: isAtt ? base + 7 : isMid ? base - 5 : 45,
    shotPower: isAtt ? base + 6 : isMid ? base + 1 : 65,
    longShots: isAtt ? base + 2 : isMid ? base + 3 : 50,
    passing: isMid ? base + 6 : isAtt ? base - 2 : base - 6,
    vision: isMid ? base + 5 : isAtt ? base - 1 : 60,
    crossing: isAtt || pos === 'LB' || pos === 'RB' ? base + 3 : 62,
    shortPassing: isMid ? base + 8 : base + 2,
    longPassing: isMid ? base + 6 : base - 2,
    dribbling: isAtt ? base + 7 : isMid ? base + 4 : 64,
    ballControl: isAtt || isMid ? base + 6 : base - 4,
    agility: isAtt ? base + 7 : isMid ? base + 2 : 66,
    balance: isAtt ? base + 5 : base,
    defending: isDef ? base + 7 : pos === 'CDM' ? base + 5 : 44,
    interceptions: isDef ? base + 7 : pos === 'CDM' ? base + 6 : 45,
    standingTackle: isDef ? base + 8 : pos === 'CDM' ? base + 6 : 42,
    slidingTackle: isDef ? base + 6 : 40,
    strength: isDef || pos === 'ST' ? base + 5 : base - 2,
    stamina: base + 4,
    reactions: base + 3,
    heading: isDef || pos === 'ST' ? base + 6 : 60,
    gkDiving: isGK ? base + 6 : 15,
    gkHandling: isGK ? base + 5 : 12,
    gkKicking: isGK ? base + 4 : 20,
    gkPositioning: isGK ? base + 6 : 14,
    gkReflexes: isGK ? base + 7 : 16,
    ...custom,
  }

  return attrs
}

function makePlayer(
  id: string,
  name: string,
  shortName: string,
  num: number,
  pos: Position,
  nat: string,
  overall: number,
  tier: 'world-class' | 'star' | 'regular' = 'star',
  custom: Partial<PlayerAttributes> = {}
): Player {
  return {
    id,
    name,
    shortName,
    shirtNumber: num,
    position: pos,
    secondaryPositions: [],
    nationality: nat,
    age: 26,
    height: 182,
    weight: 76,
    preferredFoot: 'Right',
    overall,
    attributes: makeAttributes(pos, tier, custom),
  }
}

